/**
 * The spike's PdfiumNative. Methods added here are called by name through SpikeEngine.call and
 * take a docId (a string) instead of PdfDocumentObject. The patch on @embedpdf/engines makes
 * `pdfiumModule` and `cache` protected, so later checks can reach PDFium directly.
 */
export class SpikeNative extends PdfiumNative {
  private readonly requestedFonts: string[];
  private readonly docs = new Map<string, PdfDocumentObject>();

  constructor(module: WrappedPdfiumModule, options: PdfiumEngineOptions = {}) {
    const requested: string[] = [];
    const fallback = options.fontFallback;
    const load = fallback?.fontLoader;
    super(module, {
      ...options,
      fontFallback: fallback && {
        ...fallback,
        fontLoader: (url) => {
          requested.push(url);
          return load ? load(url) : null;
        },
      },
    });
    this.requestedFonts = requested;
  }

  /** Every fallback-font URL PDFium asked for, in order (the fallback manager caches, so once per file). */
  fontRequests(): string[] {
    return [...this.requestedFonts];
  }

  async openBuffer(docId: string, content: ArrayBuffer, password?: string): Promise<SpikeDoc> {
    const doc = await this.openDocumentBuffer({ id: docId, content }, { password }).toPromise();
    this.docs.set(docId, doc);
    return {
      docId,
      pageCount: doc.pageCount,
      pages: doc.pages.map((p) => ({ width: p.size.width, height: p.size.height, rotation: ((p.rotation * 90) % 360) as 0 | 90 | 180 | 270 })),
    };
  }

  /**
   * Every char on the page with its PDFium geometry. Runs come from getPageGeometry. Its boxes do not: it
   * rounds them to whole device pixels at 1 px per point (FPDF_PageToDevice), up to 0.5 pt off, which is
   * 0.67 CSS px at 100% and 1.33 px at 200%. So the boxes are read here, unrounded, from the same
   * FPDFText_GetLooseCharBox, with FPDFText_GetCharBox, GetCharAngle, IsGenerated, GetFontSize and GetMatrix.
   */
  getGlyphs(docId: string, pageIndex: number): PageGlyphs {
    const doc = this.doc(docId);
    const page = doc.pages[pageIndex];
    if (!page) throw new Error(`page ${pageIndex} out of range (0–${doc.pageCount - 1})`);
    const geometry = settled(this.getPageGeometry(doc, page));
    const runs = geometry.runs.map((r) => ({ start: r.charStart, end: r.charStart + r.glyphs.length }));

    const m = this.pdfiumModule;
    const heap = m.pdfium;
    const pageCtx = this.cache.getContext(doc.id)!.acquirePage(pageIndex);
    const mem = heap.wasmExports.malloc(64);
    try {
      const textPage = pageCtx.getTextPage();
      const count = m.FPDFText_CountChars(textPage);
      const f32 = (offset: number) => heap.getValue(mem + offset, 'float');
      const f64 = (offset: number) => heap.getValue(mem + offset, 'double');
      // The crop box's top-left is the origin of top-left page space.
      m.FPDF_GetPageBoundingBox(pageCtx.pagePtr, mem);
      const left = f32(0);
      const top = f32(4);
      const rect = (l: number, t: number, r: number, b: number): Rect => ({ x: l - left, y: top - t, width: r - l, height: t - b });
      const text = this.pageText(textPage, count);

      const glyphs: Glyph[] = [];
      for (let i = 0; i < count; i++) {
        m.FPDFText_GetLooseCharBox(textPage, i, mem); // FS_RECTF: left, top, right, bottom
        const box = rect(f32(0), f32(4), f32(8), f32(12));
        m.FPDFText_GetCharBox(textPage, i, mem, mem + 8, mem + 16, mem + 24); // doubles: left, right, bottom, top
        const tight = rect(f64(0), f64(24), f64(8), f64(16));
        m.FPDFText_GetMatrix(textPage, i, mem); // FS_MATRIX: a b c d e f (floats)
        const fontSize = m.FPDFText_GetFontSize(textPage, i) * Math.hypot(f32(8), f32(12));
        const angle = Math.round(((m.FPDFText_GetCharAngle(textPage, i) * 180) / Math.PI) * 1000) / 1000;
        glyphs.push({ index: i, text: text[i] ?? '', box, tight, fontSize, angle: angle % 360, generated: m.FPDFText_IsGenerated(textPage, i) === 1 });
      }
      return { pageIndex, glyphs, runs };
    } finally {
      heap.wasmExports.free(mem);
      pageCtx.release();
    }
  }

  /** PDFium's text for chars [start, start + count): FPDFText_GetText through getTextSlices (which strips U+FFFE and the like). */
  getTextRange(docId: string, pageIndex: number, start: number, count: number): string {
    return settled(this.getTextSlices(this.doc(docId), [{ pageIndex, charIndex: start, charCount: count }]))[0] ?? '';
  }

  /**
   * The glyph outlines of chars [charStart, charStart + charCount), for drawing bold over the page (P0-5). Chars
   * without a glyph (generated, whitespace) are left out. Per char:
   *   1. its text object (FPDFText_GetTextObject), that object's font (FPDFTextObj_GetFont) and size (FPDFTextObj_GetFontSize);
   *   2. the glyph path, FPDFFont_GetGlyphPath(font, argument, size), trying the argument forms of GlyphArgForm in turn
   *      (see glyphArguments);
   *   3. its segments, in ems, transformed by size × the char's matrix (FPDFText_GetMatrix, whose translation is the
   *      text object's) and moved to the char's origin (FPDFText_GetCharOrigin);
   *   4. flipped to a top-left origin and written as SVG path data.
   */
  getGlyphOutlines(docId: string, pageIndex: number, charStart: number, charCount: number): GlyphOutline[] {
    return this.outlines(docId, pageIndex, charStart, charCount);
  }

  /** How getGlyphOutlines found each glyph of the same chars (the Phase 2 GLYPH_ARG decision). */
  glyphArgForms(docId: string, pageIndex: number, charStart: number, charCount: number): GlyphArgForms {
    const tally: GlyphArgForms = { forms: { unicode: 0, charcode: 0, ligature: 0, hyphen: 0 }, sharedGlyph: 0, noGlyph: 0, failed: [] };
    this.outlines(docId, pageIndex, charStart, charCount, tally);
    return tally;
  }

  /** The PDFium functions getGlyphOutlines calls that the wrapped module or the wasm does not export. */
  missingGlyphFunctions(): string[] {
    const wrapped = this.pdfiumModule as unknown as Record<string, unknown>;
    const exported = this.pdfiumModule.pdfium.wasmExports as unknown as Record<string, unknown>;
    return GLYPH_FUNCTIONS.filter((name) => typeof wrapped[name] !== 'function' || typeof exported[name] !== 'function');
  }

  /** The functions missingGlyphFunctions checks. */
  glyphFunctions(): string[] {
    return [...GLYPH_FUNCTIONS];
  }

  /** The PDFium functions the P0-10 methods call that the wasm does not export (they are called as wasm exports). */
  missingObjectFunctions(): string[] {
    const exported = this.pdfiumModule.pdfium.wasmExports as unknown as Record<string, unknown>;
    return OBJECT_FUNCTIONS.filter((name) => typeof exported[name] !== 'function');
  }

  /**
   * The page's objects (P0-10), depth first in content order. For each: FPDFPageObj_GetType, GetBounds and
   * GetMarkedContentID; for an image, FPDFImageObj_GetImagePixelSize and GetImageFilter(Count); for a path,
   * FPDFPath_CountSegments and GetDrawMode. With recurseForms, each form XObject is followed by its own objects
   * (FPDFFormObj_CountObjects/GetObject), whose bounds are mapped to the page through the forms' matrices
   * (FPDFPageObj_GetMatrix). The walk stops once it holds maxObjects objects or has run budgetMs (checked every 64
   * objects; the clock starts once the page is loaded) and sets `truncated`. The loop calls the wasm exports directly.
   */
  getPageObjects(docId: string, pageIndex: number, opts: { recurseForms: boolean; maxObjects: number; budgetMs: number }): PageObjectsResult {
    const start = performance.now();
    const doc = this.doc(docId);
    if (!doc.pages[pageIndex]) throw new Error(`page ${pageIndex} out of range (0–${doc.pageCount - 1})`);
    const x = this.exports();
    const h = this.heap();
    const pageCtx = this.cache.getContext(doc.id)!.acquirePage(pageIndex);
    // The budget runs from here: loading a page that is not loaded yet (the viewer has drawn it by the time it looks
    // for figures) must not use up the walk's time. elapsedMs still covers the whole call.
    const walkStart = performance.now();
    const mem = x.malloc(64);
    const objects: PageObjectInfo[] = [];
    let truncated = false;
    try {
      const crop = this.cropBox(pageCtx.pagePtr, mem);
      const visit = (obj: number, depth: number, matrix: Matrix | null): boolean => {
        if (objects.length >= opts.maxObjects || ((objects.length & 63) === 0 && performance.now() - walkStart > opts.budgetMs)) {
          truncated = true;
          return false;
        }
        const type = PAGE_OBJECT_TYPES[x.FPDFPageObj_GetType(obj)] ?? 'unknown';
        let [l, b, r, t] = [0, 0, 0, 0];
        if (x.FPDFPageObj_GetBounds(obj, mem, mem + 4, mem + 8, mem + 12)) {
          [l, b, r, t] = [h.float(mem), h.float(mem + 4), h.float(mem + 8), h.float(mem + 12)];
          if (matrix) [l, b, r, t] = transformBox(matrix, l, b, r, t);
        }
        const info: PageObjectInfo = {
          type,
          bounds: { x: l - crop.left, y: crop.top - t, width: r - l, height: t - b },
          formDepth: depth,
          markedContentId: x.FPDFPageObj_GetMarkedContentID(obj),
        };
        if (type === 'image') {
          x.FPDFImageObj_GetImagePixelSize(obj, mem, mem + 4);
          info.image = { pixelWidth: h.int(mem), pixelHeight: h.int(mem + 4), filters: this.imageFilters(obj) };
        } else if (type === 'path') {
          x.FPDFPath_GetDrawMode(obj, mem, mem + 4); // int fill mode (0 = none), FPDF_BOOL stroke
          info.path = { segmentCount: x.FPDFPath_CountSegments(obj), filled: h.int(mem) !== 0, stroked: h.int(mem + 4) !== 0 };
        }
        objects.push(info);
        if (type === 'form' && opts.recurseForms) {
          x.FPDFPageObj_GetMatrix(obj, mem); // FS_MATRIX: the form matrix, form space → its parent's space
          const own: Matrix = [h.float(mem), h.float(mem + 4), h.float(mem + 8), h.float(mem + 12), h.float(mem + 16), h.float(mem + 20)];
          const toPage = matrix ? concat(own, matrix) : own;
          const count = x.FPDFFormObj_CountObjects(obj);
          for (let k = 0; k < count; k++) if (!visit(x.FPDFFormObj_GetObject(obj, k), depth + 1, toPage)) return false;
        }
        return true;
      };
      const count = x.FPDFPage_CountObjects(pageCtx.pagePtr);
      for (let i = 0; i < count; i++) if (!visit(x.FPDFPage_GetObject(pageCtx.pagePtr, i), 0, null)) break;
    } finally {
      x.free(mem);
      pageCtx.release();
    }
    return { objects, truncated, elapsedMs: round2(performance.now() - start) };
  }

  /**
   * The page's structure tree (tagged PDF): FPDF_StructTree_GetForPage, then each element's FPDF_StructElement_GetType,
   * GetAltText, GetActualText and marked-content ids (GetMarkedContentIdCount/AtIndex), and its element children
   * (CountChildren/GetChildAtIndex; marked-content kids are not elements and are skipped), to depth 32. [] when the
   * page has no tree. PDFium returns an empty string for a missing /Alt or /ActualText, so both read null when empty.
   */
  getStructTree(docId: string, pageIndex: number): StructElement[] {
    const doc = this.doc(docId);
    if (!doc.pages[pageIndex]) throw new Error(`page ${pageIndex} out of range (0–${doc.pageCount - 1})`);
    const x = this.exports();
    const h = this.heap();
    const pageCtx = this.cache.getContext(doc.id)!.acquirePage(pageIndex);
    const tree = x.FPDF_StructTree_GetForPage(pageCtx.pagePtr);
    try {
      if (!tree) return [];
      // UTF-16LE with a NUL; the call returns the byte count, NUL included, whatever the buffer.
      const read16 = (fn: (el: number, buf: number, len: number) => number, el: number): string => {
        const bytes = fn(el, 0, 0);
        if (bytes <= 2) return '';
        const buf = x.malloc(bytes);
        try {
          fn(el, buf, bytes);
          return h.utf16(buf, bytes / 2 - 1);
        } finally {
          x.free(buf);
        }
      };
      const element = (el: number, depth: number): StructElement => {
        const markedContentIds: number[] = [];
        const ids = x.FPDF_StructElement_GetMarkedContentIdCount(el);
        for (let k = 0; k < ids; k++) {
          const id = x.FPDF_StructElement_GetMarkedContentIdAtIndex(el, k);
          if (id >= 0) markedContentIds.push(id);
        }
        const children: StructElement[] = [];
        if (depth < STRUCT_MAX_DEPTH) {
          const kids = x.FPDF_StructElement_CountChildren(el);
          for (let k = 0; k < kids; k++) {
            const child = x.FPDF_StructElement_GetChildAtIndex(el, k);
            if (child) children.push(element(child, depth + 1));
          }
        }
        return {
          type: read16(x.FPDF_StructElement_GetType, el),
          altText: read16(x.FPDF_StructElement_GetAltText, el) || null,
          actualText: read16(x.FPDF_StructElement_GetActualText, el) || null,
          markedContentIds,
          children,
        };
      };
      const out: StructElement[] = [];
      const count = x.FPDF_StructTree_CountChildren(tree);
      for (let k = 0; k < count; k++) {
        const el = x.FPDF_StructTree_GetChildAtIndex(tree, k);
        if (el) out.push(element(el, 1));
      }
      return out;
    } finally {
      if (tree) x.FPDF_StructTree_Close(tree);
      pageCtx.release();
    }
  }

  /**
   * The page's text as runs: its chars in index order, a new run whenever FPDFText_GetTextObject changes or the
   * baseline (FPDFText_GetCharOrigin's y) moves by more than half the run's font size. PDFium's generated line
   * breaks ('\r', '\n') end a run and belong to none; a generated space belongs to a run only when the run goes on
   * after it. `text` is FPDFText_GetText over the run's chars, `rect` the union of their FPDFText_GetLooseCharBox, and
   * `fontSize` FPDFTextObj_GetFontSize × the vertical scale of the first char's FPDFText_GetMatrix (see TextRun).
   */
  // @ts-expect-error The brief's getPageTextRuns(docId, pageIndex) replaces PdfiumNative's own getPageTextRuns(doc, page)
  // (font/colour runs). Nothing in PdfiumNative calls it; only the stock worker's runner does, by message, and this
  // spike's worker never sends that message.
  override getPageTextRuns(docId: string, pageIndex: number): TextRun[] {
    const doc = this.doc(docId);
    if (!doc.pages[pageIndex]) throw new Error(`page ${pageIndex} out of range (0–${doc.pageCount - 1})`);
    const x = this.exports();
    const h = this.heap();
    const pageCtx = this.cache.getContext(doc.id)!.acquirePage(pageIndex);
    const mem = x.malloc(64);
    try {
      const crop = this.cropBox(pageCtx.pagePtr, mem);
      const textPage = pageCtx.getTextPage();
      const count = x.FPDFText_CountChars(textPage);
      const buf = x.malloc(2 * (count + 1));
      let text: string;
      try {
        x.FPDFText_GetText(textPage, 0, count, buf);
        text = h.utf16(buf, count);
      } finally {
        x.free(buf);
      }

      const runs: TextRun[] = [];
      let run: { start: number; end: number; obj: number; baseline: number; size: number; l: number; t: number; r: number; b: number } | null = null;
      const close = () => {
        if (!run) return;
        runs.push({
          text: text.slice(run.start, run.end),
          rect: { x: run.l - crop.left, y: crop.top - run.t, width: run.r - run.l, height: run.t - run.b },
          fontSize: run.size,
          charStart: run.start,
          charCount: run.end - run.start,
        });
        run = null;
      };
      for (let i = 0; i < count; i++) {
        const ch = text.charCodeAt(i);
        if (ch === 0x0d || ch === 0x0a) {
          close();
          continue;
        }
        if (x.FPDFText_IsGenerated(textPage, i) === 1) continue; // inside the run only if a later char extends it
        const obj = x.FPDFText_GetTextObject(textPage, i);
        x.FPDFText_GetCharOrigin(textPage, i, mem, mem + 8);
        const baseline = h.double(mem + 8);
        if (run && (obj !== run.obj || Math.abs(baseline - run.baseline) > run.size / 2)) close();
        x.FPDFText_GetLooseCharBox(textPage, i, mem); // FS_RECTF: left, top, right, bottom
        const [l, t, r, b] = [h.float(mem), h.float(mem + 4), h.float(mem + 8), h.float(mem + 12)];
        if (run) {
          run.end = i + 1;
          run.l = Math.min(run.l, l);
          run.t = Math.max(run.t, t);
          run.r = Math.max(run.r, r);
          run.b = Math.min(run.b, b);
          continue;
        }
        let size = 0;
        if (obj && x.FPDFTextObj_GetFontSize(obj, mem)) {
          const tf = h.float(mem);
          x.FPDFText_GetMatrix(textPage, i, mem); // FS_MATRIX: a b c d e f
          size = tf * Math.hypot(h.float(mem + 8), h.float(mem + 12));
        }
        run = { start: i, end: i + 1, obj, baseline, size: size > 0 ? size : t - b, l, t, r, b };
      }
      close();
      return runs;
    } finally {
      x.free(mem);
      pageCtx.release();
    }
  }

  /**
   * Figures on the page (P0-10, research 06 §3.2): getPageObjects with the production limits, getStructTree and
   * getPageTextRuns, then findFigures (src/figures/find-figures.ts). `elapsedMs` covers all of it, in the worker.
   */
  detectFigures(docId: string, pageIndex: number): DetectFiguresResult {
    const start = performance.now();
    const list = this.getPageObjects(docId, pageIndex, FIGURE_OBJECT_LIMITS);
    const afterObjects = performance.now();
    const struct = this.getStructTree(docId, pageIndex);
    const afterStruct = performance.now();
    const runs = this.getPageTextRuns(docId, pageIndex);
    const afterRuns = performance.now();
    const figures = findFigures({ page: this.pageSize(docId, pageIndex), objects: list.objects, truncated: list.truncated, runs, struct });
    const end = performance.now();
    return {
      figures,
      objectCount: list.objects.length,
      elapsedMs: round2(end - start),
      truncated: list.truncated,
      phases: { objectsMs: round2(afterObjects - start), structMs: round2(afterStruct - afterObjects), runsMs: round2(afterRuns - afterStruct), findMs: round2(end - afterRuns) },
    };
  }

  private exportsCache?: Exports;
  private heapCache?: Heap;
  private exports(): Exports {
    return (this.exportsCache ??= this.pdfiumModule.pdfium.wasmExports as unknown as Exports);
  }
  private heap(): Heap {
    return (this.heapCache ??= new Heap(this.exports().memory));
  }

  /** FPDF_GetPageBoundingBox (the crop box within the media box), in PDF space: left, top, right, bottom. */
  private cropBox(pagePtr: number, mem: number): { left: number; top: number; right: number; bottom: number } {
    const x = this.exports();
    const h = this.heap();
    x.FPDF_GetPageBoundingBox(pagePtr, mem);
    return { left: h.float(mem), top: h.float(mem + 4), right: h.float(mem + 8), bottom: h.float(mem + 12) };
  }

  /** The crop box's size in points, unrotated (the space PageObjectInfo and TextRun rects are in). */
  private pageSize(docId: string, pageIndex: number): { width: number; height: number } {
    const doc = this.doc(docId);
    const x = this.exports();
    const pageCtx = this.cache.getContext(doc.id)!.acquirePage(pageIndex);
    const mem = x.malloc(16);
    try {
      const crop = this.cropBox(pageCtx.pagePtr, mem);
      return { width: crop.right - crop.left, height: crop.top - crop.bottom };
    } finally {
      x.free(mem);
      pageCtx.release();
    }
  }

  /** FPDFImageObj_GetImageFilter for each of the image's filters (ASCII names such as DCTDecode). */
  private imageFilters(obj: number): string[] {
    const x = this.exports();
    const filters: string[] = [];
    const count = x.FPDFImageObj_GetImageFilterCount(obj);
    for (let k = 0; k < count; k++) {
      const bytes = x.FPDFImageObj_GetImageFilter(obj, k, 0, 0);
      if (bytes <= 1) continue;
      const buf = x.malloc(bytes);
      try {
        x.FPDFImageObj_GetImageFilter(obj, k, buf, bytes);
        filters.push(this.heap().bytes(buf, bytes - 1));
      } finally {
        x.free(buf);
      }
    }
    return filters;
  }

  private outlines(docId: string, pageIndex: number, charStart: number, charCount: number, tally?: GlyphArgForms): GlyphOutline[] {
    const doc = this.doc(docId);
    if (!doc.pages[pageIndex]) throw new Error(`page ${pageIndex} out of range (0–${doc.pageCount - 1})`);
    const m = this.pdfiumModule;
    const heap = m.pdfium;
    const pageCtx = this.cache.getContext(doc.id)!.acquirePage(pageIndex);
    const mem = heap.wasmExports.malloc(64);
    try {
      const textPage = pageCtx.getTextPage();
      const total = m.FPDFText_CountChars(textPage);
      const start = Math.max(0, charStart);
      const end = Math.min(total, charStart + charCount);
      const f32 = (offset: number) => heap.getValue(mem + offset, 'float');
      const f64 = (offset: number) => heap.getValue(mem + offset, 'double');
      m.FPDF_GetPageBoundingBox(pageCtx.pagePtr, mem);
      const left = f32(0);
      const top = f32(4);
      const num = (v: number) => String(Math.round(v * 1000) / 1000);

      // PDFium expands a char code with several Unicode chars (a ligature, a surrogate pair) into that many chars,
      // which share the text object and the origin. They are one glyph.
      const textObject = (i: number) => (m.FPDFText_IsGenerated(textPage, i) === 1 ? 0 : m.FPDFText_GetTextObject(textPage, i));
      const origin = (i: number): [number, number] => {
        m.FPDFText_GetCharOrigin(textPage, i, mem, mem + 8);
        return [f64(0), f64(8)];
      };
      const sameGlyph = (a: number, b: number) => {
        const obj = textObject(a);
        if (!obj || obj !== textObject(b)) return false;
        const [ax, ay] = origin(a);
        const [bx, by] = origin(b);
        return ax === bx && ay === by;
      };

      const out: GlyphOutline[] = [];
      let i = start;
      while (i < end) {
        const obj = textObject(i);
        if (!obj) {
          if (tally) tally.noGlyph++;
          i++;
          continue;
        }
        let first = i;
        while (first > 0 && sameGlyph(first - 1, first)) first--; // the range starts inside a ligature
        let next = i + 1;
        while (next < total && sameGlyph(next - 1, next)) next++;
        const units: number[] = [];
        for (let k = first; k < next; k++) units.push(m.FPDFText_GetUnicode(textPage, k));
        const shared = Math.min(next, end) - i - 1;

        const font = m.FPDFTextObj_GetFont(obj);
        m.FPDFTextObj_GetFontSize(obj, mem);
        const size = f32(0);
        let path = 0;
        let form: GlyphArgForm | undefined;
        for (const candidate of this.glyphArguments(textPage, first, units)) {
          const p = m.FPDFFont_GetGlyphPath(font, candidate.arg, size);
          if (p && m.FPDFGlyphPath_CountGlyphSegments(p) > 0) {
            path = p;
            form = candidate.form;
            break;
          }
        }
        if (tally) tally.sharedGlyph += shared;
        if (!path) {
          if (tally && unitsText(units).trim() !== '') tally.failed.push({ charIndex: i, unicode: units[0]! });
          else if (tally) tally.noGlyph++;
          i = next;
          continue;
        }
        if (tally) tally.forms[form!]++;

        // Glyph space (ems) → page space: size × the char matrix's linear part, at the char's origin.
        m.FPDFText_GetMatrix(textPage, first, mem);
        const a = size * f32(0);
        const b = size * f32(4);
        const c = size * f32(8);
        const d = size * f32(12);
        const [ox, oy] = origin(first);
        let svg = '';
        let curve: string[] = [];
        const segments = m.FPDFGlyphPath_CountGlyphSegments(path);
        for (let s = 0; s < segments; s++) {
          const segment = m.FPDFGlyphPath_GetGlyphPathSegment(path, s);
          m.FPDFPathSegment_GetPoint(segment, mem, mem + 4);
          const gx = f32(0);
          const gy = f32(4);
          const xy = `${num(ox + a * gx + c * gy - left)} ${num(top - (oy + b * gx + d * gy))}`;
          const type = m.FPDFPathSegment_GetType(segment);
          if (type === FPDF_SEGMENT_MOVETO) svg += `M${xy}`;
          else if (type === FPDF_SEGMENT_LINETO) svg += `L${xy}`;
          else if (type === FPDF_SEGMENT_BEZIERTO) {
            curve.push(xy); // a cubic is three BEZIERTO points: two controls, then the end
            if (curve.length === 3) {
              svg += `C${curve.join(' ')}`;
              curve = [];
            }
          }
          if (m.FPDFPathSegment_GetClose(segment)) svg += 'Z';
        }
        out.push({ charIndex: i, d: svg });
        i = next;
      }
      return out;
    } finally {
      heap.wasmExports.free(mem);
      pageCtx.release();
    }
  }

  /**
   * FPDFFont_GetGlyphPath arguments to try, in order, for the glyph of chars [first, first + units.length). The call
   * maps its argument through the font's CharCodeFromUnicode, so every form is a Unicode value. PDFium has no call
   * that returns a char's code: for a char without Unicode, FPDFText_GetUnicode already returns the code (the
   * `charcode` form), so retrying "with the char code" is the same call.
   */
  private glyphArguments(textPage: number, first: number, units: number[]): { arg: number; form: GlyphArgForm }[] {
    const m = this.pdfiumModule;
    if (units.length === 1 && m.FPDFText_IsHyphen(textPage, first) === 1) {
      return [{ arg: 0x2d, form: 'hyphen' }, { arg: 0x2010, form: 'hyphen' }, { arg: units[0]!, form: 'unicode' }];
    }
    const own = m.FPDFText_HasUnicodeMapError(textPage, first) === 1 ? 'charcode' : 'unicode';
    if (units.length === 1) return [{ arg: units[0]!, form: own }];
    const text = unitsText(units);
    const composed = [...text.normalize('NFC')];
    const out: { arg: number; form: GlyphArgForm }[] = [];
    if (composed.length === 1) out.push({ arg: composed[0]!.codePointAt(0)!, form: 'unicode' }); // a surrogate pair, a decomposed accent
    if (LIGATURES[text]) out.push({ arg: LIGATURES[text], form: 'ligature' });
    out.push({ arg: units[0]!, form: own }); // last resort: the first char's own glyph (half a ligature)
    return out;
  }

  /** RGBA pixels of a page (or of `rect` within it) at `scale` device pixels per point. */
  renderRaw(docId: string, pageIndex: number, scale: number, rect?: SpikeRect): Promise<ImageDataLike> {
    const doc = this.doc(docId);
    const page = doc.pages[pageIndex];
    if (!page) throw new Error(`page ${pageIndex} out of range (0–${doc.pageCount - 1})`);
    const task = rect
      ? this.renderPageRect(doc, page, { origin: { x: rect.x, y: rect.y }, size: { width: rect.width, height: rect.height } }, { scaleFactor: scale })
      : this.renderPageRaw(doc, page, { scaleFactor: scale });
    return task.toPromise();
  }

  async closeDoc(docId: string): Promise<void> {
    await this.closeDocument(this.doc(docId)).toPromise();
    this.docs.delete(docId);
  }

  protected doc(docId: string): PdfDocumentObject {
    const doc = this.docs.get(docId);
    if (!doc) throw new Error(`document ${docId} is not open`);
    return doc;
  }

  /** FPDFText_GetText for the whole page: one UTF-16 code unit per char index. */
  private pageText(textPage: number, count: number): string {
    const heap = this.pdfiumModule.pdfium;
    const buf = heap.wasmExports.malloc(2 * (count + 1));
    try {
      this.pdfiumModule.FPDFText_GetText(textPage, 0, count, buf);
      let out = '';
      for (let i = 0; i < count; i++) out += String.fromCharCode(heap.getValue(buf + 2 * i, 'i16') & 0xffff);
      return out;
    } finally {
      heap.wasmExports.free(buf);
    }
  }
}

/** The bounding box (PDF space: left, bottom, right, top) of a box mapped through `m`. */
function transformBox(m: Matrix, l: number, b: number, r: number, t: number): [number, number, number, number] {
  const [a, bb, c, d, e, f] = m;
  const xs = [a * l + c * b + e, a * r + c * b + e, a * l + c * t + e, a * r + c * t + e];
  const ys = [bb * l + d * b + f, bb * r + d * b + f, bb * l + d * t + f, bb * r + d * t + f];
  return [Math.min(...xs), Math.min(...ys), Math.max(...xs), Math.max(...ys)];
}

/** FPDFText_GetUnicode values as text: surrogate halves or whole code points, as PDFium gives them; U+FFFD past U+10FFFF. */
function unitsText(units: number[]): string {
  return units.map((u) => (u >= 0 && u <= 0x10ffff ? String.fromCodePoint(u) : '\ufffd')).join('');
}

/** The value of a PdfTask that has already settled (PDFium calls are synchronous; the task wraps the result). */
function settled<T>(task: PdfTask<T>): T {
  let out: { value: T } | undefined;
  let failure: unknown;
  task.wait(
    (value) => (out = { value }),
    (error) => (failure = error),
  );
  if (out) return out.value;
  throw new Error(`PDFium task did not settle synchronously: ${JSON.stringify(failure ?? 'pending')}`);
}
