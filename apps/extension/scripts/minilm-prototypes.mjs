// `node scripts/minilm-prototypes.mjs [--check | --write]` (default --check; `--check` is a step of `build` and `build:e2e`).
//
// The tie-breaker compares a PDF's text with 13 reference sentences (src/viewer/filter/prototypes.ts). Their vectors are
// computed once and stored in that file; this script keeps them honest.
//   --check  recomputes every vector with the same code the viewer runs (wordpiece.ts, embedder.ts) on the same model file,
//            and fails (exit 1) when the sentences, the model or any stored vector is not what the file says it was made from.
//   --write  recomputes them and rewrites the generated block of prototypes.ts. Run it after changing a sentence or the
//            pinned model (scripts/fetch-minilm.mjs must have put that model in public/models/minilm/).
// The model runs on onnxruntime-web in Node, single thread, wasm: the same engine as in the extension.
import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import * as ort from 'onnxruntime-web';
import { createServer } from 'vite';
import { MINILM_FILES } from './fetch-minilm.mjs';

const root = fileURLToPath(new URL('..', import.meta.url));
const modelDir = join(root, 'public/models/minilm');
const protoFile = join(root, 'src/viewer/filter/prototypes.ts');
const write = process.argv.includes('--write');
/** Two unit vectors this close (cosine) are the same vector for the filter: it moves a score by at most ±2 from a difference of 0.2. */
const SAME = 0.9999;

const fail = (message) => {
  console.error(`minilm-prototypes: ${message}`);
  process.exit(1);
};

const model = MINILM_FILES.find((f) => f.name === 'model_quantized.onnx');
const vocab = MINILM_FILES.find((f) => f.name === 'vocab.txt');
let modelBytes;
let vocabText;
try {
  modelBytes = await readFile(join(modelDir, model.name));
  vocabText = await readFile(join(modelDir, vocab.name), 'utf8');
} catch {
  fail('the model is not in apps/extension/public/models/minilm/. Run `node scripts/fetch-minilm.mjs` first.');
}
const modelSha = createHash('sha256').update(modelBytes).digest('hex');
if (modelSha !== model.sha256) fail(`the model file's sha256 is ${modelSha}, not the pinned ${model.sha256}. Run \`node scripts/fetch-minilm.mjs\`.`);

// A passing check is remembered (in node_modules, so a reinstall forgets it) until the model, the sentences or the code that
// makes the vectors change, so the many builds of an e2e loop do not each pay for loading the model.
const stampFile = join(root, 'node_modules/.cache/sop/minilm-prototypes-ok');
const sources = await Promise.all(['prototypes.ts', 'wordpiece.ts', 'embedder.ts'].map((f) => readFile(join(root, 'src/viewer/filter', f), 'utf8')));
const stamp = createHash('sha256').update(modelSha).update(ort.env.versions.common ?? '').update(sources.join('\0')).update(await readFile(fileURLToPath(import.meta.url))).digest('hex');
if (!write && (await readFile(stampFile, 'utf8').catch(() => '')) === stamp) {
  console.log('minilm-prototypes: stored vectors match the model (unchanged since the last check)');
  process.exit(0);
}

const server = await createServer({
  root,
  configFile: false,
  appType: 'custom',
  logLevel: 'error',
  server: { middlewareMode: true, hmr: false, watch: null },
  optimizeDeps: { noDiscovery: true },
});
let embedder;
try {
  const { createEmbedder } = await server.ssrLoadModule('/src/viewer/filter/embedder.ts');
  const p = await server.ssrLoadModule('/src/viewer/filter/prototypes.ts');
  ort.env.wasm.numThreads = 1;
  ort.env.logLevel = 'error';
  embedder = await createEmbedder(ort, new Uint8Array(modelBytes), vocabText);

  const sets = [
    ['learning', p.LEARNING_SENTENCES, p.LEARNING_VECTORS],
    ['notLearning', p.NOT_LEARNING_SENTENCES, p.NOT_LEARNING_VECTORS],
  ];
  const fresh = { learning: [], notLearning: [] };
  for (const [kind, sentences] of sets) for (const sentence of sentences) fresh[kind].push(await embedder.embed(sentence));

  if (write) {
    const block = [
      '// <generated by scripts/minilm-prototypes.mjs --write>',
      `export const PROTOTYPE_MODEL_SHA256 = '${modelSha}';`,
      'export const LEARNING_VECTORS: readonly string[] = [',
      ...fresh.learning.map((v) => `  '${p.encodeVector(v)}',`),
      '];',
      'export const NOT_LEARNING_VECTORS: readonly string[] = [',
      ...fresh.notLearning.map((v) => `  '${p.encodeVector(v)}',`),
      '];',
      '// </generated>',
    ].join('\n');
    const text = await readFile(protoFile, 'utf8');
    const next = text.replace(/\/\/ <generated by [\s\S]*?\/\/ <\/generated>/, block);
    if (next === text && !text.includes(block)) fail('the generated block was not found in prototypes.ts');
    await writeFile(protoFile, next);
    console.log(`minilm-prototypes: wrote ${fresh.learning.length + fresh.notLearning.length} vectors to ${protoFile.slice(root.length)}`);
  } else {
    if (p.PROTOTYPE_MODEL_SHA256 !== modelSha) fail(`prototypes.ts was made from model ${p.PROTOTYPE_MODEL_SHA256 || '(none)'}, not ${modelSha}. Run \`node scripts/minilm-prototypes.mjs --write\`.`);
    let lowest = 1;
    for (const [kind, sentences, stored] of sets) {
      if (stored.length !== sentences.length) fail(`${kind}: ${sentences.length} sentences but ${stored.length} stored vectors. Run \`node scripts/minilm-prototypes.mjs --write\`.`);
      stored.forEach((b64, i) => {
        const a = p.decodeVector(b64);
        const b = fresh[kind][i];
        if (a.length !== b.length) fail(`${kind} ${i + 1}: the stored vector has ${a.length} numbers, the model gives ${b.length}.`);
        let dot = 0;
        for (let k = 0; k < a.length; k++) dot += a[k] * b[k];
        lowest = Math.min(lowest, dot);
        if (!(dot >= SAME)) fail(`${kind} ${i + 1} ("${sentences[i].slice(0, 40)}…"): the stored vector differs from the model's (cosine ${dot.toFixed(6)}). Run \`node scripts/minilm-prototypes.mjs --write\`.`);
      });
    }
    await mkdir(dirname(stampFile), { recursive: true });
    await writeFile(stampFile, stamp);
    console.log(`minilm-prototypes: ${fresh.learning.length + fresh.notLearning.length} stored vectors match the model (lowest cosine ${lowest.toFixed(6)})`);
  }
} finally {
  await embedder?.dispose();
  await server.close();
}
