// `node scripts/minilm-subjects.mjs [--check | --write]` (default --check; `--check` is a step of `build` and `build:e2e`).
//
// A topic is named after the closest of about 300 academic subjects (spec R92b; packages/core/src/categorise/subjects.json). Their meaning
// vectors are made once and stored in src/categorise/subject-vectors.ts; this script keeps them honest, the way minilm-prototypes.mjs does for
// the filter's reference sentences.
//   --check  recomputes every vector with the same code the extension runs (wordpiece.ts, embedder.ts) on the same model file, and fails
//            (exit 1) when the list, the model or any stored vector is not what the file says it was made from.
//   --write  recomputes them and rewrites the generated block of subject-vectors.ts. Run it after changing the list or the pinned model
//            (scripts/fetch-minilm.mjs must have put that model in public/models/minilm/).
// The model runs on onnxruntime-web in Node, single thread, wasm: the same engine as in the extension.
import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import * as ort from 'onnxruntime-web';
import { createServer } from 'vite';
import { MINILM_FILES } from './fetch-minilm.mjs';

const root = fileURLToPath(new URL('..', import.meta.url));
const modelDir = join(root, 'public/models/minilm');
const vectorsFile = join(root, 'src/categorise/subject-vectors.ts');
const listFile = join(root, '../../packages/core/src/categorise/subjects.json');
const write = process.argv.includes('--write');
/** A stored vector (a byte a number) and the model's must be this close (cosine). Rounding to a byte costs about 0.00007; a vector of another subject, text or model is far below this, a single changed byte is within the rounding. */
const SAME = 0.9995;

const fail = (message) => {
  console.error(`minilm-subjects: ${message}`);
  process.exit(1);
};

const model = MINILM_FILES.find((f) => f.name === 'model_quantized.onnx');
const vocab = MINILM_FILES.find((f) => f.name === 'vocab.txt');
let modelBytes;
let vocabText;
try {
  modelBytes = await readFile(join(modelDir, model.name));
  vocabText = await readFile(join(modelDir, vocab.name), 'utf8');
} catch {
  fail('the model is not in apps/extension/public/models/minilm/. Run `node scripts/fetch-minilm.mjs` first.');
}
const modelSha = createHash('sha256').update(modelBytes).digest('hex');
if (modelSha !== model.sha256) fail(`the model file's sha256 is ${modelSha}, not the pinned ${model.sha256}. Run \`node scripts/fetch-minilm.mjs\`.`);

const names = JSON.parse(await readFile(listFile, 'utf8'));
if (!Array.isArray(names) || names.length === 0 || names.some((n) => typeof n !== 'string' || n.trim() === '') || new Set(names).size !== names.length) {
  fail('subjects.json must be a list of distinct, non-empty names.');
}
const listSha = createHash('sha256').update(JSON.stringify(names)).digest('hex');

// A passing check is remembered (in node_modules, so a reinstall forgets it) until the list, the model or the code that makes the vectors
// change, so the many builds of an e2e loop do not each pay for loading the model.
const stampFile = join(root, 'node_modules/.cache/sop/minilm-subjects-ok');
const sources = await Promise.all(['wordpiece.ts', 'embedder.ts'].map((f) => readFile(join(root, 'src/viewer/filter', f), 'utf8')));
const stamp = createHash('sha256')
  .update(modelSha)
  .update(listSha)
  .update(ort.env.versions.common ?? '')
  .update(sources.join('\0'))
  .update(await readFile(vectorsFile, 'utf8'))
  .update(await readFile(fileURLToPath(import.meta.url)))
  .digest('hex');
if (!write && (await readFile(stampFile, 'utf8').catch(() => '')) === stamp) {
  console.log('minilm-subjects: stored vectors match the model (unchanged since the last check)');
  process.exit(0);
}

const server = await createServer({
  root,
  configFile: false,
  appType: 'custom',
  logLevel: 'error',
  server: { middlewareMode: true, hmr: false, watch: null },
  optimizeDeps: { noDiscovery: true },
});
let embedder;
try {
  const { createEmbedder } = await server.ssrLoadModule('/src/viewer/filter/embedder.ts');
  const v = await server.ssrLoadModule('/src/categorise/subject-vectors.ts');
  ort.env.wasm.numThreads = 1;
  ort.env.logLevel = 'error';
  embedder = await createEmbedder(ort, new Uint8Array(modelBytes), vocabText);
  const fresh = [];
  for (const name of names) fresh.push(await embedder.embed(name));

  if (write) {
    const block = [
      '// <generated by scripts/minilm-subjects.mjs --write>',
      `export const SUBJECT_MODEL_SHA256 = '${modelSha}';`,
      `export const SUBJECT_LIST_SHA256 = '${listSha}';`,
      'export const SUBJECT_VECTORS: readonly string[] = [',
      ...fresh.map((vec) => `  '${v.encodeSubjectVector(vec)}',`),
      '];',
      '// </generated>',
    ].join('\n');
    const text = await readFile(vectorsFile, 'utf8');
    const next = text.replace(/\/\/ <generated by [\s\S]*?\/\/ <\/generated>/, () => block);
    if (next === text && !text.includes(block)) fail('the generated block was not found in subject-vectors.ts');
    await writeFile(vectorsFile, next);
    console.log(`minilm-subjects: wrote ${fresh.length} vectors to ${vectorsFile.slice(root.length)}`);
  } else {
    const hint = 'Run `node scripts/minilm-subjects.mjs --write`.';
    if (v.SUBJECT_MODEL_SHA256 !== modelSha) fail(`subject-vectors.ts was made from model ${v.SUBJECT_MODEL_SHA256 || '(none)'}, not ${modelSha}. ${hint}`);
    if (v.SUBJECT_LIST_SHA256 !== listSha) fail(`subject-vectors.ts was made from another list of subjects than subjects.json. ${hint}`);
    if (v.SUBJECT_VECTORS.length !== names.length) fail(`${names.length} subjects but ${v.SUBJECT_VECTORS.length} stored vectors. ${hint}`);
    let lowest = 1;
    v.SUBJECT_VECTORS.forEach((b64, i) => {
      const a = v.decodeSubjectVector(b64);
      const b = fresh[i];
      if (a.length !== b.length) fail(`"${names[i]}": the stored vector has ${a.length} numbers, the model gives ${b.length}.`);
      let dot = 0;
      for (let k = 0; k < a.length; k++) dot += a[k] * b[k];
      lowest = Math.min(lowest, dot);
      if (!(dot >= SAME)) fail(`"${names[i]}": the stored vector differs from the model's (cosine ${dot.toFixed(6)}). ${hint}`);
    });
    await mkdir(dirname(stampFile), { recursive: true });
    await writeFile(stampFile, stamp);
    console.log(`minilm-subjects: ${names.length} stored vectors match the model (lowest cosine ${lowest.toFixed(6)})`);
  }
} finally {
  await embedder?.dispose();
  await server.close();
}
