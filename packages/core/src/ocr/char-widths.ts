/** The width of a char with no entry (or a zero one): Noto Sans's mean lower-case advance. */
const FALLBACK = 540;

/** The advance of one char (a code point) in thousandths of an em. */
export function charAdvance(ch: string): number {
  const c = ch.codePointAt(0) ?? 0;
  for (const [from, widths] of RANGES) {
    if (c >= from && c < from + widths.length) return widths[c - from] || FALLBACK;
  }
  return FALLBACK;
}
