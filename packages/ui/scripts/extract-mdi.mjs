// Writes src/icons/file-pdf-box.ts from the Pictogrammers Material Design Icons set (@iconify-json/mdi).
//
//   node scripts/extract-mdi.mjs   (or: pnpm --filter @sop/ui icons:mdi)
//
// Only the icons listed in ICONS are taken, so the set that ships stays small and the licence notice stays exact.
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);

/** mdi icon name -> exported constant */
const ICONS = { 'file-pdf-box': 'FILE_PDF_BOX' };

const output = fileURLToPath(new URL('../src/icons/file-pdf-box.ts', import.meta.url));

const set = JSON.parse(readFileSync(require.resolve('@iconify-json/mdi/icons.json'), 'utf8'));
const info = JSON.parse(readFileSync(require.resolve('@iconify-json/mdi/info.json'), 'utf8'));
const { version } = JSON.parse(readFileSync(require.resolve('@iconify-json/mdi/package.json'), 'utf8'));

/** A TypeScript single-quoted string literal. */
const quote = (text) => `'${text.replaceAll('\\', '\\\\').replaceAll("'", "\\'")}'`;

function generate() {
  const lines = [
    `// Generated by packages/ui/scripts/extract-mdi.mjs from @iconify-json/mdi ${version}. Do not edit by hand.`,
    `// ${info.name} by ${info.author.name}, ${info.license.title} (${info.license.spdx}): ${info.license.url}`,
    '',
  ];
  for (const [name, constant] of Object.entries(ICONS)) {
    const icon = set.icons[name];
    if (!icon) throw new Error(`@iconify-json/mdi has no icon "${name}"`);
    const width = icon.width ?? set.width;
    const height = icon.height ?? set.height;
    lines.push(`/** mdi:${name}. The body draws with currentColor. */`);
    lines.push(`export const ${constant} = { body: ${quote(icon.body)}, width: ${width}, height: ${height} } as const;`);
  }
  return `${lines.join('\n')}\n`;
}

writeFileSync(output, generate());
console.log(`wrote ${output}`);
